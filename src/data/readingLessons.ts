// Tự động gộp các câu hỏi bổ sung vào 10 bài thơ gốc để cả 26 bài đều có đủ 6 câu hỏi
for (const poem of POEM_READING_LIBRARY) {
  const extras = EXTRA_QUESTIONS_FOR_BASE_POEMS[poem.id];
  if (extras && poem.questions.length < 6) {
    poem.questions = [...poem.questions, ...extras];
  }
}

/**
 * Rút ngẫu nhiên `count` (mặc định 5) câu hỏi không trùng lặp từ kho câu hỏi của bài thơ,
 * đảm bảo luôn kết thúc bằng câu hỏi liên hệ kỹ năng sống (`life_skill`) nếu có,
 * và đánh số lại nhãn `Câu 1/5 .. Câu 5/5`.
 */
export function drawQuestionsForPoem(
  poem: PoemReadingItem,
  count = 5,
): PoemQuizItem[] {
  const lifeSkillQs = poem.questions.filter((q) => q.type === "life_skill");
  const otherQs = poem.questions.filter((q) => q.type !== "life_skill");

  const pickedOthers = drawNonRepeatingItems(
    `reading:poem-q-other:${poem.id}`,
    otherQs,
    Math.max(1, count - (lifeSkillQs.length > 0 ? 1 : 0)),
    (q) => q.id,
  );

  const pickedLife =
    lifeSkillQs.length > 0
      ? drawNonRepeatingItems(
          `reading:poem-q-life:${poem.id}`,
          lifeSkillQs,
          1,
          (q) => q.id,
        )
      : [];

  const combined = [...pickedOthers, ...pickedLife].slice(0, count);
  const total = combined.length;

  return combined.map((q, idx) => {
    const typeLabel =
      q.type === "comprehension"
        ? "Hiểu nội dung"
        : q.type === "fill_blank"
          ? "Điền từ thơ"
          : "Bài học của Nấm";
    return {
      ...q,
      badgeLabel: `Câu ${idx + 1}/${total} · ${typeLabel}`,
    };
  });
}

/**
 * Rút 1 bài thơ chưa học trong mức độ `level` (1 hoặc 2) bằng bộ nhớ chống lặp.
 */
export function drawRandomPoemByLevel(
  level: 1 | 2,
  excludePoemId?: string,
): PoemReadingItem {
  const levelPoems = POEM_READING_LIBRARY.filter((p) => p.level === level);
  return drawSingleNonRepeatingItem(
    `reading:poem-lv:${level}`,
    levelPoems,
    (p) => p.id,
    excludePoemId,
  );
}

