export interface SharedAssetQueryFilter {
  themeGroup?: AssetThemeGroup | "all";
  subject?: SubjectId;
  primaryColor?: AssetPrimaryColor;
  activityVerbEn?: string;
  soundEffect?: AssetSoundEffect;
  searchText?: string;
}

/**
 * Bộ máy tìm kiếm & lọc đồ vật trong Kho Dùng Chung theo bất kỳ tiêu chí nào:
 * - Nhóm chủ đề (themeGroup)
 * - Môn học sử dụng (subject)
 * - Màu sắc chủ đạo (primaryColor)
 * - Động từ hoạt động (activityVerbEn)
 * - Hiệu ứng âm thanh (soundEffect)
 * - Từ khóa tự do tiếng Việt có dấu / không dấu / tiếng Anh (searchText)
 */
export function querySharedAssets(
  filter: SharedAssetQueryFilter = {},
): SharedAssetMetadata[] {
  const normalizedQuery = filter.searchText
    ? filter.searchText.toLowerCase().trim()
    : "";
  const asciiQuery = normalizedQuery
    ? removeVietnameseTones(normalizedQuery)
    : "";

  return SHARED_ASSET_CATALOG.filter((item) => {
    if (
      filter.themeGroup &&
      filter.themeGroup !== "all" &&
      item.themeGroup !== filter.themeGroup
    ) {
      return false;
    }
    if (filter.subject && !item.usedInSubjects.includes(filter.subject)) {
      return false;
    }
    if (filter.primaryColor && item.primaryColor !== filter.primaryColor) {
      return false;
    }
    if (
      filter.activityVerbEn &&
      item.activityVerbEn.toLowerCase() !== filter.activityVerbEn.toLowerCase()
    ) {
      return false;
    }
    if (filter.soundEffect && item.soundEffect !== filter.soundEffect) {
      return false;
    }
    if (normalizedQuery) {
      const matched = item.searchKeywords.some(
        (kw) => kw.includes(normalizedQuery) || kw.includes(asciiQuery),
      );
      if (!matched) return false;
    }
    return true;
  });
}

