export interface IdeaAssetRecommendation {
  ideaQuery: string;
  matchingFramesAndScenes: ReusableFrameSceneAsset[];
  matchingItems3D: SharedAssetMetadata[];
}

/**
 * Hàm gợi ý thông minh ("Reuse-First Recommender"):
 * Khi bạn có ý tưởng bài học, mini-game, hoặc module mới, truyền từ khóa ý tưởng vào đây
 * để lấy ngay danh sách Khung Bảng / Bối Cảnh (kể cả các frame cũ đang cất kho)
 * và Đồ Vật 3D phù hợp mà không cần phải tạo ảnh mới.
 */
export function recommendAssetsForIdea(
  ideaQuery: string,
  maxItems = 12,
): IdeaAssetRecommendation {
  const normalized = ideaQuery.toLowerCase().trim();
  const ascii = removeVietnameseTones(normalized);
  const words = Array.from(
    new Set(
      [...normalized.split(/\s+/), ...ascii.split(/\s+/)].filter(
        (w) => w.length >= 2,
      ),
    ),
  );

  const scoreKeywords = (keywords: string[]): number => {
    if (words.length === 0) return 1;
    let score = 0;
    const joined = keywords.join(" ");
    if (joined.includes(normalized) || joined.includes(ascii)) {
      score += 5;
    }
    for (const w of words) {
      if (keywords.some((kw) => kw.includes(w))) {
        score += 2;
      }
    }
    return score;
  };

  const matchingFramesAndScenes = REUSABLE_FRAME_AND_SCENE_VAULT.map((f) => ({
    asset: f,
    // Ưu tiên nhẹ cho các frame/scene đang cất kho ("archived_reusable") để tận dụng tối đa tài nguyên
    score:
      scoreKeywords(f.searchKeywords) +
      (f.status === "archived_reusable" ? 0.5 : 0),
  }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 6)
    .map((entry) => entry.asset);

  const matchingItems3D = SHARED_ASSET_CATALOG.map((item) => ({
    asset: item,
    score: scoreKeywords(item.searchKeywords),
  }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxItems)
    .map((entry) => entry.asset);

  return {
    ideaQuery,
    matchingFramesAndScenes,
    matchingItems3D,
  };
}

