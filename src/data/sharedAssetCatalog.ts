/**
 * Chuẩn Metadata Đa Chiều cho từng bức ảnh 3D trong Kho Ảnh Dùng Chung Toàn Hệ Thống
 * (Single Source of Truth cho Kỹ Năng Sống, Học Đọc Tiếng Việt, Tiếng Anh, Toán, Trò Chơi & Vở Sticker)
 */
export interface SharedAssetMetadata {
  id: string;
  imageUrl: string;
  icon: string;
  /** Tên Tiếng Việt đầy đủ (hiển thị ở Kỹ năng sống, Toán, Vở Sticker) */
  name: string;
  /** Từ ghép Tiếng Việt ngắn gọn (2-3 tiếng) để bé 5 tuổi đánh vần & ghép chữ */
  readingWordVi: string;
  /** Các âm tiết Tiếng Việt tách sẵn phục vụ bài Học Đọc ghép chữ */
  syllablesVi: string[];
  /** Tên Tiếng Anh đầy đủ */
  englishName: string;
  /** Từ vựng Tiếng Anh cốt lõi */
  englishWord: string;
  /** Phiên âm Quốc tế IPA */
  pronunciationIpa: string;
  /** Câu đọc mẫu Tiếng Việt (TTS) */
  spokenVi: string;
  /** Câu đọc mẫu Tiếng Anh (TTS) */
  spokenEn: string;
  /** Màu sắc chủ đạo thực tế của hình ảnh (đã đối chiếu trực tiếp file PNG) */
  primaryColor: AssetPrimaryColor;
  /** Tên màu sắc Tiếng Việt */
  colorLabelVi: string;
  /** Tên màu sắc Tiếng Anh */
  colorLabelEn: string;
  /** Hoạt động gắn liền bằng Tiếng Việt */
  activityLabelVi: string;
  /** Động từ hành động Tiếng Anh */
  activityVerbEn: string;
  /** Cụm từ hoạt động Tiếng Anh */
  activityPhraseEn: string;
  /** Mã hiệu ứng âm thanh tương tác */
  soundEffect: AssetSoundEffect;
  /** Mô tả âm thanh sinh động cho bé */
  soundLabelVi: string;
  /** Phân loại chi tiết */
  category: AssetCategoryType;
  /** Nhóm chủ đề lớn */
  themeGroup: AssetThemeGroup;
  /** Nhãn danh mục Tiếng Việt */
  categoryLabel: string;
  /** Danh sách các môn học sử dụng ảnh này */
  usedInSubjects: SubjectId[];
  /** Danh sách các khu vực/tính năng sử dụng ảnh này */
  usedInZones: string[];
  /** Bộ từ khóa tìm kiếm nhanh (Tiếng Việt, Tiếng Anh, màu sắc, hoạt động, âm thanh) */
  searchKeywords: string[];
}

interface RawSharedAssetSeed {
  id: string;
  imageUrl: string;
  icon: string;
  name: string;
  readingWordVi: string;
  englishName: string;
  englishWord?: string;
  pronunciationIpa: string;
  primaryColor: AssetPrimaryColor;
  colorLabelVi: string;
  colorLabelEn: string;
  activityLabelVi: string;
  activityVerbEn: string;
  activityPhraseEn: string;
  soundEffect: AssetSoundEffect;
  soundLabelVi: string;
  category: AssetCategoryType;
  themeGroup: AssetThemeGroup;
  categoryLabel: string;
  usedInSubjects?: SubjectId[];
  usedInZones?: string[];
  extraTags?: string[];
}

function removeVietnameseTones(str: string): string {
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase();
}

function buildAssetMetadata(seed: RawSharedAssetSeed): SharedAssetMetadata {
  const readingUpper = seed.readingWordVi.trim().toUpperCase();
  const syllablesVi = readingUpper.split(/\s+/).filter(Boolean);
  const englishWord = seed.englishWord || seed.englishName;
  const usedInSubjects: SubjectId[] = seed.usedInSubjects || [
    "lifeskills",
    "reading",
    "english",
    "math",
    "minigame",
  ];
  const usedInZones =
    seed.usedInZones ||
    (seed.themeGroup === "lifeskills"
      ? [
          "Kỹ năng sống",
          "Học đọc Tiếng Việt",
          "Từ vựng Tiếng Anh",
          "Toán đếm & Siêu thị",
          "Bộ Sticker Kỹ năng sống",
          "Lật thẻ trí nhớ",
        ]
      : [
          "Toán đếm & Siêu thị",
          "Từ vựng Tiếng Anh",
          "Học đọc Tiếng Việt",
          "Vở Sticker Nhiệm vụ",
          "Lật thẻ trí nhớ",
        ]);

  const spokenVi = `${seed.name}. ${seed.activityLabelVi}. Màu ${seed.colorLabelVi.toLowerCase()}.`;
  const spokenEn = `${seed.englishName}. ${seed.activityPhraseEn}!`;

  const rawKeywords = [
    seed.id,
    seed.name,
    seed.readingWordVi,
    seed.englishName,
    englishWord,
    seed.colorLabelVi,
    seed.colorLabelEn,
    seed.primaryColor,
    seed.activityLabelVi,
    seed.activityVerbEn,
    seed.activityPhraseEn,
    seed.soundEffect,
    seed.soundLabelVi,
    seed.categoryLabel,
    seed.themeGroup,
    ...usedInZones,
    ...(seed.extraTags || []),
  ];

  const searchKeywords = Array.from(
    new Set(
      rawKeywords.flatMap((kw) => {
        const lower = kw.toLowerCase().trim();
        const ascii = removeVietnameseTones(lower);
        return lower === ascii ? [lower] : [lower, ascii];
      }),
    ),
  );

  return {
    id: seed.id,
    imageUrl: seed.imageUrl,
    icon: seed.icon,
    name: seed.name,
    readingWordVi: readingUpper,
    syllablesVi,
    englishName: seed.englishName,
    englishWord,
    pronunciationIpa: seed.pronunciationIpa,
    spokenVi,
    spokenEn,
    primaryColor: seed.primaryColor,
    colorLabelVi: seed.colorLabelVi,
    colorLabelEn: seed.colorLabelEn,
    activityLabelVi: seed.activityLabelVi,
    activityVerbEn: seed.activityVerbEn,
    activityPhraseEn: seed.activityPhraseEn,
    soundEffect: seed.soundEffect,
    soundLabelVi: seed.soundLabelVi,
    category: seed.category,
    themeGroup: seed.themeGroup,
    categoryLabel: seed.categoryLabel,
    usedInSubjects,
    usedInZones,
    searchKeywords,
  };
}

